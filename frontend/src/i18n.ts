export type TranslationKey = keyof typeof strings["zh-CN"];

export function translate(locale: Locale, key: TranslationKey): string {
  return strings[locale]?.[key] ?? strings.en[key] ?? key;
}

export function useLocaleText(locale: Locale) {
  return (key: TranslationKey) => translate(locale, key);
}

export function formatClock(locale: Locale, timestamp = Date.now()): string {
  return new Date(timestamp).toLocaleTimeString(locale, { hour12: false });
}
